#!/usr/bin/env bash
# Compiles the MCLA iOS texture load shaders (*.cs.xesl here) to SPIR-V headers the way
# xenia's `xb buildshaders` does: glslangValidator, spirv-opt -O, spirv-dis, and a C array.
# The XeSL headers they include come from xenia at a fixed commit (BSD 3-clause).
# The headers go into SDK patch 09 (src/graphics/shaders/vulkan_spirv/).
#
# Usage: build-shaders.sh <output folder>
# Needs glslangValidator, spirv-opt and spirv-dis (Ubuntu: glslang-tools spirv-tools), curl.
set -euo pipefail

XENIA_COMMIT=95a5c3ee250f80c3b9d139658649d9ffb6db3eec
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$(mkdir -p "$1" && cd "$1" && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

raw="https://raw.githubusercontent.com/xenia-project/xenia/$XENIA_COMMIT/src/xenia"
for f in ui/shaders/xesl.xesli gpu/shaders/endian.xesli gpu/shaders/pixel_formats.xesli \
         gpu/shaders/texture_address.xesli gpu/shaders/texture_load.xesli; do
  curl -fsSL "$raw/$f" -o "$WORK/$(basename "$f")"
done
cp "$HERE"/*.xesl "$HERE"/*.xesli "$WORK/"

cd "$WORK"
for src in *.cs.xesl; do
  id="${src%.xesl}"
  id="${id//./_}"
  echo "- $src > $id.h"
  printf '#version 460\n#extension GL_EXT_control_flow_attributes : require\n#extension GL_EXT_samplerless_texture_functions : require\n#extension GL_GOOGLE_include_directive : require\n#include "%s"\n' "$src" |
    glslangValidator --stdin -DSHADING_LANGUAGE_GLSL_XE=1 -S comp -o "$id.glslang.spv" -V -I"$WORK"
  spirv-opt -O --canonicalize-ids "$id.glslang.spv" -o "$id.spv" 2>/dev/null ||
    spirv-opt -O "$id.glslang.spv" -o "$id.spv"
  spirv-dis -o "$id.txt" "$id.spv"
  python3 - "$id" "$OUT/$id.h" <<'EOF'
import sys
name, out = sys.argv[1], sys.argv[2]
words = open(name + '.spv', 'rb').read()
assert len(words) % 4 == 0
with open(out, 'w', newline='\n') as f:
    f.write('// Generated by ios/sdk/shaders/build-shaders.sh (as `xb buildshaders`).\n#if 0\n')
    dis = open(name + '.txt').read()
    f.write(dis if dis.endswith('\n') else dis + '\n')
    f.write('#endif\n\nconst uint32_t %s[] = {' % name)
    for i in range(0, len(words), 4):
        f.write(('\n    ' if (i // 4) % 6 == 0 else ' ') +
                '0x%08X,' % int.from_bytes(words[i:i + 4], 'little'))
    f.write('\n};\n')
EOF
done
ls -l "$OUT"
